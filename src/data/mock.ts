export function getBookBySlug(slug: string) {
  return books.find((b) => b.slug === slug);
}

export function getBookById(id: string) {
  return books.find((b) => b.id === id);
}

export function getAuthorBySlug(slug: string) {
  return authors.find((a) => a.slug === slug);
}

export function getBooksByAuthor(authorId: string) {
  return books.filter((b) => b.authorId === authorId);
}

export function getBooksByCategory(categoryId: string) {
  return books.filter((b) => b.categoryIds.includes(categoryId));
}

export function getCollectionBySlug(slug: string) {
  return collections.find((c) => c.slug === slug);
}

export function getReviewsForBook(bookId: string) {
  return reviews.filter((r) => r.bookId === bookId);
}

export function searchBooks(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return books;
  return books.filter(
    (b) =>
      b.title.toLowerCase().includes(q) ||
      b.authorName.toLowerCase().includes(q) ||
      b.isbn.includes(q) ||
      b.genres.some((g) => g.toLowerCase().includes(q)) ||
      b.publisherName.toLowerCase().includes(q) ||
      b.tags.some((t) => t.toLowerCase().includes(q)) ||
      b.description.toLowerCase().includes(q)
  );
}

export function formatMoney(amount: number, currency = siteConfig.currencySymbol) {
  return `${currency}${amount.toLocaleString("en-GH", {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  })}`;
}

export function lowestPrice(book: Book) {
  return Math.min(...book.formats.map((f) => f.price));
}

export function relatedBooks(book: Book, limit = 4) {
  return books
    .filter(
      (b) =>
        b.id !== book.id &&
        (b.authorId === book.authorId ||
          b.genres.some((g) => book.genres.includes(g)) ||
          b.categoryIds.some((c) => book.categoryIds.includes(c)))
    )
    .slice(0, limit);
}
